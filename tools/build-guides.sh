#!/usr/bin/env bash
# يعيد توليد أدلة الويب من مصادرها في dev-docs/guides.
#
# **لماذا ملفٌّ واحد يجمعها؟** لأن كل دليلٍ يحتاج ستة معاملات (النكهة
# والعنوان والوصف وسبب الحجب) — ومن يعيد توليده بعد شهرٍ لن يتذكّرها،
# فيولّده بوصفٍ مختلف أو ينسى وسم `noindex`. الأمر هنا مكتوبٌ مرة واحدة:
#
#     bash tools/build-guides.sh
#
# شغّله **كلما عدّل مساعد التطبيق ملفاً في dev-docs/guides** — فالصفحة
# صورةٌ من المصدر لا نسخة مستقلة، ولا تتحدّث من تلقاء نفسها.
#
# دليل الكابتن (docs/guide/driver/) ليس هنا: صُمِّم بيدٍ في خمسة دروس
# مصوّرة لا فصولاً نصّية، فلا يقبل قالب المولِّد.
set -euo pipefail
cd "$(dirname "$0")/.."

python3 tools/build-guide.py \
  "dev-docs/guides/دليل-المطعم.md" docs/guide/restaurant/index.html restaurant \
  "دليل المطعم" \
  "كيف تدير طلبات مطعمك في زاد جو: دورة الطلب بثلاث ضغطات، وقراءة حساباتك، وإدارة منيوك."

python3 tools/build-guide.py \
  "dev-docs/guides/دليل-العميل.md" docs/guide/customer/index.html customer \
  "دليل العميل" \
  "كيف تطلب من زاد جو: خطوات الطلب، وتتبّع كابتنك، وقراءة فاتورتك، والإلغاء والاسترداد." \
  "يُخفى مع باب العميل ويظهران معاً: صفحة الطلب مخفيّة أثناء التجربة، ودليلٌ يشرح شاشةً لا يستطيع الزائر بلوغها يوقعه في حيرة لا فائدة. عند الفتح للجمهور: احذف المعامل السادس من أمر التوليد وأعد التوليد، واحذف /guide/customer/ من robots.txt، واضبط TRIAL_MODE = false في docs/index.html."

python3 tools/build-guide.py \
  "dev-docs/guides/دليل-الإدارة.md" docs/guide/admin/index.html admin \
  "دليل الإدارة" \
  "لوحة زاد جو للإدارة: المتابعة الحية، وسجلّ الطلبات، وقواعد المال والإلغاء، والمطاعم والكباتن، والشكاوى وسجلّ التدقيق." \
  "صفحةٌ إدارية لا عامة: تشرح كيف يُصرف المال وتُدار الحسابات. لا تُفهرَس ولا تُربَط من صفحةٍ عامة؛ يبلغها المدير من لوحته وحدها. محجوبة أيضاً في robots.txt."
