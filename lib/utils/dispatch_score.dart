// درجة ترشيح الكابتن (نفذ ٣) — دالة نقية مستخرَجة من الإسناد التلقائي
// كي يحرسها CI: هذا الترتيب يقرّر رزق الكباتن، وتغييره سهواً (قلب
// إشارة، تبديل وزن) لن يُلحَظ في مراجعة عين بل في اختبار يفشل.
//
// المعادلة: ثلثا الدرجة لمعدل القبول وثلثها للتقييم (مقيساً من ٥ إلى
// ٠..١). القبول أثقل لأنه سلوك يومي تجاه المنصّة يملك الكابتن تغييره
// غداً، والتقييم انطباع عملاء يتجمّد بعد حين فلا يصلح فيصلاً وحده.
// ومن لا تاريخ عروض له يُحسب قبوله كاملاً (1.0) لا صفراً — كابتن جديد
// عومل بصفرٍ لن تصله عروض أصلاً ليبني معدلاً.

/// درجة الترشيح المركّبة — الأعلى يُرشَّح أولاً بين المتساوين قرباً.
double dispatchScore({double? acceptanceRate, required double rating}) =>
    (acceptanceRate ?? 1.0) * 2 + (rating / 5.0);
